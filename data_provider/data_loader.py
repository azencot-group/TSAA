class Dataset_Pred(Dataset):
    def __init__(self, root_path, flag='pred', size=None,
                 features='S', data_path='ETTh1.csv',
                 target='OT', scale=True, inverse=False, timeenc=0, freq='15min', cols=None):
        # size [seq_len, label_len, pred_len]
        if size == None:
            self.seq_len = 24 * 4 * 4
            self.label_len = 24 * 4
            self.pred_len = 24 * 4
        else:
            self.seq_len = size[0]
            self.label_len = size[1]
            self.pred_len = size[2]
        
        assert flag in ['pred']

        self.features = features
        self.target = target
        self.scale = scale
        self.inverse = inverse
        self.timeenc = timeenc
        self.freq = freq
        self.cols = cols
        self.root_path = root_path
        self.data_path = data_path
        self.__read_data__()

    def __read_data__(self):
        self.scaler = StandardScaler()
        df_raw = pd.read_csv(os.path.join(self.root_path, self.data_path))
        
        if self.cols:
            cols = self.cols.copy()
            cols.remove(self.target)
        else:
            cols = list(df_raw.columns)
            cols.remove(self.target)
            cols.remove('date')
        df_raw = df_raw[['date'] + cols + [self.target]]
        border1 = len(df_raw) - self.seq_len
        border2 = len(df_raw)

        if self.features == 'M' or self.features == 'MS':
            cols_data = df_raw.columns[1:]
            df_data = df_raw[cols_data]
        elif self.features == 'S':
            df_data = df_raw[[self.target]]

        if self.scale:
            self.scaler.fit(df_data.values)
            data = self.scaler.transform(df_data.values)
        else:
            data = df_data.values

        tmp_stamp = df_raw[['date']][border1:border2]
        tmp_stamp['date'] = pd.to_datetime(tmp_stamp.date)
        pred_dates = pd.date_range(tmp_stamp.date.values[-1], periods=self.pred_len + 1, freq=self.freq)

        df_stamp = pd.DataFrame(columns=['date'])
        df_stamp.date = list(tmp_stamp.date.values) + list(pred_dates[1:])
        if self.timeenc == 0:
            df_stamp['month'] = df_stamp.date.apply(lambda row: row.month, 1)
            df_stamp['day'] = df_stamp.date.apply(lambda row: row.day, 1)
            df_stamp['weekday'] = df_stamp.date.apply(lambda row: row.weekday(), 1)
            df_stamp['hour'] = df_stamp.date.apply(lambda row: row.hour, 1)
            df_stamp['minute'] = df_stamp.date.apply(lambda row: row.minute, 1)
            df_stamp['minute'] = df_stamp.minute.map(lambda x: x // 15)
            data_stamp = df_stamp.drop(['date'], 1).values
        elif self.timeenc == 1:
            data_stamp = time_features(pd.to_datetime(df_stamp['date'].values), freq=self.freq)
            data_stamp = data_stamp.transpose(1, 0)

        self.data_x = data[border1:border2]
        if self.inverse:
            self.data_y = df_data.values[border1:border2]
        else:
            self.data_y = data[border1:border2]
        self.data_stamp = data_stamp

    def __getitem__(self, index):
        s_begin = index
        s_end = s_begin + self.seq_len
        r_begin = s_end - self.label_len
        r_end = r_begin + self.label_len + self.pred_len

        seq_x = self.data_x[s_begin:s_end]
        if self.inverse:
            seq_y = self.data_x[r_begin:r_begin + self.label_len]
        else:
            seq_y = self.data_y[r_begin:r_begin + self.label_len]
        seq_x_mark = self.data_stamp[s_begin:s_end]
        seq_y_mark = self.data_stamp[r_begin:r_end]

        return seq_x, seq_y, seq_x_mark, seq_y_mark

    def __len__(self):
        return len(self.data_x) - self.seq_len + 1

    def inverse_transform(self, data):
        return self.scaler.inverse_transform(data)


class Dataset_Custom_aa(Dataset_Custom):
    def __init__(self, root_path, flag='train', size=None,
                 features='S', data_path='ETTh1.csv',
                 target='OT', scale=True, timeenc=0, freq='h',
                 stl=False, seasonality=12, stl_name=None, kfold=1, kfold_i=1, kfold_flag='train'):

        self.stl_name = stl_name
        self.stl = stl
        self.seasonality = seasonality
        self.flag = flag
        self.augment = True
        self.kfold = kfold
        self.kfold_i = kfold_i
        self.kfold_flag = kfold_flag
        super().__init__(root_path, flag, size, features, data_path, target, scale, timeenc, freq)

    def __read_data__(self):
        super().__read_data__()
        if self.seasonality is not None and self.stl:
            cur_path = os.path.join(os.getcwd(), f'dataset/STL decomp/{self.stl_name}_{self.features}.pt')
            if os.path.isfile(cur_path):
                print("import stl")
                all_stl = torch.load(cur_path)
                self.data_trend = all_stl[0]
                self.data_seas = all_stl[1]
                print("import successful")
            else:
                start = timeit.default_timer()
                print("compute stl")
                data_for_stl = self.data_x.T
                stl = PySTL(data_for_stl, self.seasonality)
                self.data_trend = stl[0].T
                self.data_seas = stl[1].T

                stop = timeit.default_timer()
                print('stl complete, time: ', stop - start) 
                dir_path = os.path.join(os.getcwd(), 'dataset/STL decomp/')
                if not os.path.exists(dir_path):
                    os.makedirs(dir_path, exist_ok=True)
                all_stl = torch.cat([self.data_trend.unsqueeze(0),
                                    self.data_seas.unsqueeze(0)])
                torch.save(all_stl, cur_path)
            plt.show()
        else:
            self.data_trend = None
            self.data_seas = None  

        if self.kfold > 1:
            len_data = len(self.data_x)
            k_len = len_data // self.kfold
            train_len = int(k_len * 0.7)
            border1s = [k_len * i for i in range(self.kfold + 1)]
            border2s = [k_len * i + train_len for i in range(self.kfold)]

            if self.flag == 'train':
                border1 = border1s[self.kfold_i]
                border2 = border2s[self.kfold_i]
            elif self.kfold_flag == 'val':
                border1 = border2s[self.kfold_i]
                border2 = border1s[self.kfold_i + 1]
            self.data_x = self.data_x[border1:border2]
            self.data_y = self.data_y[border1:border2]
            if self.stl:
                self.data_trend = self.data_trend[border1:border2]
                self.data_seas = self.data_seas[border1:border2]

    def __getitem__(self, index):
        seq_x, seq_y, seq_x_mark, seq_y_mark = super().__getitem__(index)
        s_begin = index   
        s_end = s_begin + self.seq_len
        r_begin = s_end - self.label_len
        r_end = r_begin + self.label_len + self.pred_len

        if not np.array_equal(seq_x[-self.label_len:], seq_y[:self.label_len]):
            raise Exception("seq_y and seq_x do not match")

        if self.stl:
            seq_trend = self.data_trend[s_begin:r_end]
            seq_seas = self.data_seas[s_begin:r_end]
            return seq_x, seq_y, seq_x_mark, seq_y_mark, seq_trend, seq_seas
        else:
            return seq_x, seq_y, seq_x_mark, seq_y_mark


